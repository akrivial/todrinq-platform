# --- TD3 Actor (outputs continuous actions) ---
def create_actor(state_dim, action_low, action_high):
    inputs = layers.Input(shape=(state_dim,))
    x = layers.Dense(64, activation='relu')(inputs)
    x = layers.Dense(64, activation='relu')(x)
    outputs = layers.Dense(1, activation='tanh')(x)  # output in [-1,1]
    outputs = outputs * (action_high - action_low)/2 + (action_high + action_low)/2  # scale to [low, high]
    model = tf.keras.Model(inputs, outputs)
    return model

# --- TD3 Critic (Q-value estimation) ---
def create_critic(state_dim):
    state_input = layers.Input(shape=(state_dim,))
    action_input = layers.Input(shape=(1,))
    x = layers.Concatenate()([state_input, action_input])
    x = layers.Dense(64, activation='relu')(x)
    x = layers.Dense(64, activation='relu')(x)
    q_value = layers.Dense(1)(x)
    model = tf.keras.Model([state_input, action_input], q_value)
    return model

# --- Replay Buffer ---
class ReplayBuffer:
    def __init__(self, max_size=int(1e6)):
        self.max_size = max_size
        self.storage = []
        self.ptr = 0

    def add(self, state, action_norm, reward, next_state, done):
        """Store normalized action (action_norm in [-1,1])."""
        data = (np.array(state, dtype=np.float32),
                np.array(action_norm, dtype=np.float32),
                np.float32(reward),
                np.array(next_state, dtype=np.float32),
                np.float32(done))
        if len(self.storage) < self.max_size:
            self.storage.append(data)
        else:
            self.storage[self.ptr] = data
            self.ptr = (self.ptr + 1) % self.max_size

    def sample(self, batch_size):
        batch = random.sample(self.storage, batch_size)
        states, actions, rewards, next_states, dones = map(np.array, zip(*batch))
        # Ensure clean shapes
        states = states.astype(np.float32)              # (B, state_dim)
        actions = actions.astype(np.float32).reshape(batch_size, -1)  # (B, action_dim)
        rewards = rewards.astype(np.float32).reshape(batch_size, 1)   # (B, 1)
        next_states = next_states.astype(np.float32)    # (B, state_dim)
        dones = dones.astype(np.float32).reshape(batch_size, 1)       # (B, 1)
        return states, actions, rewards, next_states, dones

    def size(self):
        return len(self.storage)

