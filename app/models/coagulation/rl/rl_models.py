class PPOAgent:
    def __init__(self, state_dim, action_dim, action_low=1.5, action_high=6.0):
        self.state_dim = state_dim
        self.action_dim = action_dim
        self.action_low = action_low
        self.action_high = action_high

        # Hyperparameters
        self.gamma = 0.99
        self.policy_clip = 0.2
        self.actor_lr = 0.0003
        self.critic_lr = 0.001
        self.batch_size = 64
        self.epochs = 10 # Number of times to reuse the buffer data

        # Networks
        self.actor = self.build_actor()
        self.critic = self.build_critic()
        self.actor_optimizer = tf.keras.optimizers.Adam(learning_rate=self.actor_lr)
        self.critic_optimizer = tf.keras.optimizers.Adam(learning_rate=self.critic_lr)

    def build_actor(self):
        inputs = layers.Input(shape=(self.state_dim,))
        x = layers.Dense(128, activation='relu')(inputs)
        x = layers.Dense(128, activation='relu')(x)
        # Mu (Mean) of the action distribution
        mu_raw = layers.Dense(self.action_dim, activation='tanh')(x)
        # Scale tanh [-1, 1] to dosage range [1.5, 6.0]
        mu = (mu_raw +1.0) * (self.action_high - self.action_low) / 2 + self.action_low
        # Standard deviation (Log Std)
        sigma = layers.Dense(self.action_dim, activation='softplus')(x)
        return tf.keras.Model(inputs, [mu, sigma])

    def build_critic(self):
        inputs = layers.Input(shape=(self.state_dim,))
        x = layers.Dense(128, activation='relu')(inputs)
        x = layers.Dense(128, activation='relu')(x)
        values = layers.Dense(1)(x)
        return tf.keras.Model(inputs, values)

    def get_action(self, state):
        if len(state.shape) == 1:
            state = state[np.newaxis, :]

        mu, sigma = self.actor(state)
        # Add epsilon to sigma to prevent NaN
        sigma += 1e-6

        dist = tf.random.normal(shape=tf.shape(mu), mean=mu, stddev=sigma)
        action = tf.clip_by_value(dist, self.action_low, self.action_high)

        log_prob = self.log_probabilities(mu, sigma, action)

        return action.numpy().flatten(), log_prob.numpy().flatten()

    def log_probabilities(self, mu, sigma, action):
        # Gaussian Log Likelihood
        pre_sum = -0.5 * (((action - mu) / (sigma + 1e-8))**2 + 2 * tf.math.log(sigma + 1e-8) + tf.math.log(2 * np.pi))
        return tf.reduce_sum(pre_sum, axis=1)

    def train(self, states, actions, old_log_probs, rewards, next_states, dones):
        # Compute Advantages
        values = self.critic(states)
        next_values = self.critic(next_states)
        # Targets for Critic (TD error)
        targets = rewards + self.gamma * next_values * (1 - dones)
        advantages = targets - values

        for _ in range(self.epochs):
            with tf.GradientTape(persistent=True) as tape:
                # Get new log probs
                mu, sigma = self.actor(states)
                new_log_probs = self.log_probabilities(mu, sigma, actions)

                # Ratio for PPO
                ratio = tf.exp(new_log_probs - old_log_probs)

                # Clipped Objective
                surr1 = ratio * advantages
                surr2 = tf.clip_by_value(ratio, 1 - self.policy_clip, 1 + self.policy_clip) * advantages
                actor_loss = -tf.reduce_mean(tf.minimum(surr1, surr2))

                # Critic Loss (MSE)
                new_values = self.critic(states)
                critic_loss = tf.reduce_mean(tf.square(targets - new_values))

            # Apply Gradients
            actor_grads = tape.gradient(actor_loss, self.actor.trainable_variables)
            critic_grads = tape.gradient(critic_loss, self.critic.trainable_variables)

            self.actor_optimizer.apply_gradients(zip(actor_grads, self.actor.trainable_variables))
            self.critic_optimizer.apply_gradients(zip(critic_grads, self.critic.trainable_variables))
            return actor_loss, critic_loss

    def train_step(self, states, actions, old_log_probs, rewards, next_states, dones):
        # Ensure inputs are Tensors
        states = tf.convert_to_tensor(states, dtype=tf.float32)
        actions = tf.convert_to_tensor(actions, dtype=tf.float32)
        old_log_probs = tf.convert_to_tensor(old_log_probs, dtype=tf.float32)
        rewards = tf.convert_to_tensor(rewards, dtype=tf.float32)
        next_states = tf.convert_to_tensor(next_states, dtype=tf.float32)
        dones = tf.convert_to_tensor(dones, dtype=tf.float32)

        # Fix shapes: actions and log_probs often need to be (Batch, 1)
        if len(actions.shape) == 1: actions = tf.expand_dims(actions, axis=-1)
        if len(old_log_probs.shape) == 1: old_log_probs = tf.expand_dims(old_log_probs, axis=-1)

        # 1. Compute Advantages outside the epoch loop (Standard PPO)
        values = self.critic(states)
        next_values = self.critic(next_states)
        targets = rewards + self.gamma * next_values * (1 - dones)
        advantages = targets - values
        # Normalize advantages for stability
        advantages = (advantages - tf.reduce_mean(advantages)) / (tf.math.reduce_std(advantages) + 1e-8)

        for _ in range(self.epochs):
            with tf.GradientTape(persistent=True) as tape:
                mu, sigma = self.actor(states)
                new_log_probs = self.log_probabilities(mu, sigma, actions)
                if len(new_log_probs.shape) == 1: new_log_probs = tf.expand_dims(new_log_probs, axis=-1)

                # Ratio
                ratio = tf.exp(new_log_probs - old_log_probs)

                # Clipped Objective
                surr1 = ratio * advantages
                surr2 = tf.clip_by_value(ratio, 1 - self.policy_clip, 1 + self.policy_clip) * advantages
                actor_loss = -tf.reduce_mean(tf.minimum(surr1, surr2))

                # Critic Loss
                new_values = self.critic(states)
                critic_loss = tf.reduce_mean(tf.square(targets - new_values))

            # Apply Gradients
            actor_grads = tape.gradient(actor_loss, self.actor.trainable_variables)
            critic_grads = tape.gradient(critic_loss, self.critic.trainable_variables)

            self.actor_optimizer.apply_gradients(zip(actor_grads, self.actor.trainable_variables))
            self.critic_optimizer.apply_gradients(zip(critic_grads, self.critic.trainable_variables))

            del tape
        return actor_loss, critic_loss
