def get_dosage_suggestion(online_data_dict, supervised_model,flow_coag,action_map):
    """
    Takes a dictionary of sensor readings, runs it through the RL environment,
    and returns the recommended FeCl3 dosage.
    """
    # Convert the single input dictionary into a DataFrame
    df_input = pd.DataFrame([online_data_dict])
    actual_flow = flow_coag[list(flow_coag.keys())[0]] # cconvert flow number
    # Initialize the Environment with this single row
    # We pass the supervised_model here as the env needs it for internal logic
    temp_env = UnifiedCoagulationEnv(df_input, supervised_model, mode='discrete')

    # Reset the environment to get the initial state
    state, _ = temp_env.reset()

    # Prepare state for DQN (Shape: 1, state_dim)
    state_input = np.array(state, dtype=np.float32).reshape(1, -1)

    # Predict Q-values
    q_values = dqn_agent.predict(state_input, verbose=0)

    # Select best action index
    best_action_idx = np.argmax(q_values[0])

    # Map index to actual dosage
    recommended_dosage_mmol = action_map[best_action_idx]
    recommended_dosage_ml = recommended_dosage_mmol * actual_flow /192

    return recommended_dosage_mmol,recommended_dosage_ml


