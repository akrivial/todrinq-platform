@keras.saving.register_keras_serializable(package="Custom")
class ModifiedBatchNormalization(keras.layers.BatchNormalization):
    def __init__(self, **kwargs):
        # We call the parent BatchNormalization constructor
        super().__init__(**kwargs)

    def get_config(self):
        # Grabs all standard BatchNormalization parameters (momentum, epsilon, etc.)
        config = super().get_config()
        return config

@keras.saving.register_keras_serializable(package="Custom")
class PhysicsLayer(keras.layers.Layer):
    def __init__(self, physics_constant=1.0, **kwargs):
        super().__init__(**kwargs)
        # Store your custom variables here
        self.physics_constant = physics_constant

    def call(self, inputs):
        # Your physics logic goes here
        if isinstance(inputs, (list, tuple)):
            x = inputs[0]
        else:
            x = inputs
        return x * self.physics_constant

    def compute_output_shape(self, input_shape):
        if isinstance(input_shape, list):
            return input_shape[0]
        return input_shape

    def get_config(self):
        # 1. Get the base config (name, trainable status, etc.)
        config = super().get_config()
        # 2. Add your specific custom arguments to the dictionary
        config.update(
            {
                "physics_constant": self.physics_constant,
            }
        )
        return config

    @classmethod
    def from_config(cls, config):
        # This tells Keras how to instantiate the class using the config dict
        return cls(**config)


